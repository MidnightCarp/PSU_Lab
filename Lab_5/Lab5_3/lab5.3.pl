% ============================================================
% Предикат принадлежности элемента множеству (списку).
% ============================================================
member_(X, [X|_]).
member_(X, [_|T]) :- member_(X, T).

% ============================================================
% Разность множеств: A \ B — элементы A, которых нет в B.
% ============================================================
difference([], _, []).
difference([H|T], B, Result) :-
    (   member_(H, B)
    ->  difference(T, B, Result)
    ;   Result = [H|Rest],
        difference(T, B, Rest)
    ).

% ============================================================
% Объединение множеств: A ∪ B.
% ============================================================
union([], B, B).
union([H|T], B, Result) :-
    (   member_(H, B)
    ->  union(T, B, Result)
    ;   Result = [H|Rest],
        union(T, B, Rest)
    ).

% ============================================================
% Симметричная разность: A △ B = (A \ B) ∪ (B \ A).
% ============================================================
symmetric_difference(A, B, Result) :-
    difference(A, B, AminusB),
    difference(B, A, BminusA),
    union(AminusB, BminusA, Result).