% ============================================================
% Решение логической задачи о футбольных прогнозах.
% ============================================================

solve(Result) :-
    % 1. Генерируем все возможные перестановки мест для 4 команд.
    permutation([1, 2, 3, 4], [S, C, D, R]),

    % 2. Условие Ивана: ровно один прогноз верен.
    (S =:= 1 -> V1 = 1 ; V1 = 0),
    (C =:= 4 -> V2 = 1 ; V2 = 0),
    V1 + V2 =:= 1,

    % 3. Условие Сергея.
    (S >= 3 -> V3 = 1 ; V3 = 0),
    (C =:= 2 -> V4 = 1 ; V4 = 0),
    V3 + V4 =:= 1,

    % 4. Условие Петра.
    (D =:= 1 -> V5 = 1 ; V5 = 0),
    (C =< 3 -> V6 = 1 ; V6 = 0),
    V5 + V6 =:= 1,

    % 5. Условие Алексея.
    (D =:= 2 -> V7 = 1 ; V7 = 0),
    (R =:= 4 -> V8 = 1 ; V8 = 0),
    V7 + V8 =:= 1,

    % 6. Формируем результат
    Result = [sport(spartak, S), sport(cska, C), sport(dynamo, D), sport(rotor, R)].