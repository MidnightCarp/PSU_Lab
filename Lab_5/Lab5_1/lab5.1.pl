% digits(+N, -List)
% N — натуральное число, List — список его цифр.

% База: число из одной цифры
digits(N, [N]) :-
    N >= 0,
    N < 10.

% Рекурсия: N >= 10
digits(N, L) :-
    N >= 10,
    N1 is N // 10,      % отбрасываем последнюю цифру
    D  is N mod 10,     % выделяем последнюю цифру
    digits(N1, L1),     % рекурсивно получаем цифры числа N1
    append(L1, [D], L). % дописываем последнюю цифру в конец